"""Build a self-contained zip of the paper for online LaTeX editors (Prism, Overleaf).

    python make_export.py [output.zip]      (default: D:/thesis/paper-export.zip, i.e. three
                                             levels above this folder)

What goes in, all at the top level of the zip:
  * main.tex, with \\wsixteen pointed at tables/ and \\graphicspath at figures/ only;
  * references.bib and the MLSys style files (mlsys2025.sty/.bst, algorithm(ic).sty,
    fancyhdr.sty);
  * tables/<name>.tex: a SNAPSHOT of every generated table main.tex inputs from
    ../week_16_update/tables (re-run this script after report_w16.py regenerates them);
  * main.bbl, the bibliography as last built here, so citations resolve even if the
    editor does not run BibTeX (if it does, it simply rebuilds the file);
  * figures/*, if any;
  * README.txt with the settings to use.
"""
import datetime
import pathlib
import re
import subprocess
import sys
import zipfile

HERE = pathlib.Path(__file__).resolve().parent
TABLES = HERE.parent / "week_16_update" / "tables"
OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "paper-export.zip"
STYLE = ["references.bib", "mlsys2025.sty", "mlsys2025.bst", "algorithm.sty",
         "algorithmic.sty", "fancyhdr.sty"]
BS = "\\"

src = (HERE / "main.tex").read_text(encoding="utf-8")
old_tables = BS + "newcommand{" + BS + "wsixteen}{../week_16_update/tables}"
old_gpath = BS + "graphicspath{{figures/}{../figures2/}}"
assert old_tables in src, "the \\wsixteen definition changed; update make_export.py"
assert old_gpath in src, "the \\graphicspath line changed; update make_export.py"
tex = src.replace(old_tables, BS + "newcommand{" + BS + "wsixteen}{tables}")
tex = tex.replace(old_gpath, BS + "graphicspath{{figures/}}")

tables = sorted(set(re.findall(re.escape(BS + "input{" + BS + "wsixteen/") + r"([A-Za-z0-9_]+)\}", src)))
missing = [t for t in tables if not (TABLES / (t + ".tex")).exists()]
assert not missing, f"generated tables missing: {missing}"

bbl = HERE / "main.bbl"
notes = []
if not bbl.exists():
    notes.append("main.bbl missing: build once with latexmk first, or the editor must run BibTeX")
elif bbl.stat().st_mtime < (HERE / "references.bib").stat().st_mtime:
    notes.append("main.bbl is older than references.bib: rebuild with latexmk first")

try:
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE,
                            capture_output=True, text=True).stdout.strip() or "unknown"
    dirty = subprocess.run(["git", "status", "--porcelain", "--", ".", str(TABLES)], cwd=HERE,
                           capture_output=True, text=True).stdout.strip()
    if dirty:
        commit += " + uncommitted changes"
except OSError:
    commit = "unknown"

readme = f"""Paper export ({datetime.date.today()}, from commit {commit})

Main document : main.tex
Compiler      : pdfLaTeX (not XeLaTeX or LuaLaTeX), with BibTeX for the bibliography.
                main.bbl is included, so citations also work if BibTeX is not run.
Tables        : tables/*.tex are a snapshot of report/week_16_update/tables at this commit.
                They are generated by tools/ml2/report_w16.py; do not edit them here --
                re-export after they are regenerated.
Figures       : put image files in figures/.
"""

OUT.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("main.tex", tex)
    for name in STYLE:
        z.write(HERE / name, name)
    for t in tables:
        z.write(TABLES / (t + ".tex"), f"tables/{t}.tex")
    if bbl.exists():
        z.write(bbl, "main.bbl")
    figs = HERE / "figures"
    if figs.is_dir():
        for f in sorted(figs.rglob("*")):
            if f.is_file():
                z.write(f, "figures/" + f.relative_to(figs).as_posix())
    z.writestr("README.txt", readme)

print(f"wrote {OUT} ({len(tables)} tables, commit {commit})")
for n in notes:
    print("WARNING:", n)
