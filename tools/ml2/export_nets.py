#!/usr/bin/env python3
"""Export the five extra models chosen for the kernel as integer tables.

  kernel/mlnets.h       the networks / trees (struct mlnet, see kernel/mlnet.h)
  user/mlnet_names.h    name -> id, for `vmrun ml <name>`

The first five are the best kernel-observable models on validation streams, one per kind (extra_report /
the ranking in report_w15): a CNN over the aging bits (kv), set-attention (graph), a deeper MLP (kv),
ranking boosted trees (graph), boosted trees (kv).

    python3 export_nets.py
"""
from pathlib import Path

import extra_core as Z
import netint

ROOT = Path(__file__).resolve().parents[2]
MODELS = [("cnn-kv", "kv.agecnn.K.-"), ("attention-graph", "graph.setctx.K.-"), ("mlp-kv", "kv.deep.K.-"),
          ("ranktrees-graph", "graph.rank.K.trees100-leaves16"), ("trees-kv", "kv.gbdt.K.trees100-leaves16"),
          # the same five kinds trained on all workloads (ids 6-10), for the fair comparison
          ("cnn-all", "global.agecnn.K.-"), ("attention-all", "global.setctx.K.-"), ("mlp-all", "global.deep.K.-"),
          ("ranktrees-all", "global.rank.K.trees100-leaves16"), ("trees-all", "global.gbdt.K.trees100-leaves16")]


def main():
    k = ["// generated by tools/ml2/export_nets.py -- do not edit", '#include "mlnet.h"', ""]
    names = ["// generated by tools/ml2/export_nets.py -- do not edit",
             "struct ml_net_name { const char *name; int id; };", "static const struct ml_net_name ml_net_names[] = {"]
    for i, (name, src) in enumerate(MODELS, 1):
        n = netint.from_spec(Z.load_spec(src))
        k.append(f"// id {i}: {name} <- {src}")
        k.append(netint.c_struct(f"mlnet_{i}", n))
        names.append(f'  {{ "{name}", {i} }},')
        size = sum(a.size for a in n.arrays.values()) * 4
        print(f"  id {i} {name:16s} {src:36s} {size / 1024:6.1f} KB")
    k.append("static const struct mlnet *const ml_nets[] = { 0, " + ", ".join(f"&mlnet_{i}" for i in range(1, len(MODELS) + 1)) + " };")
    k.append(f"#define ML_NNETS {len(MODELS) + 1}")
    names += ["};", f"#define ML_NET_NAMES {len(MODELS)}", ""]
    (ROOT / "kernel" / "mlnets.h").write_text("\n".join(k) + "\n")
    (ROOT / "user" / "mlnet_names.h").write_text("\n".join(names))


if __name__ == "__main__":
    main()
